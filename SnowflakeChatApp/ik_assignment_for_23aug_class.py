MAX_PAGES = 200

"""This cell makes an HTTP GET request to the `START_URL` using the defined headers and timeout, and stores the response in the `resp` variable."""

resp = requests.get(START_URL, headers=HEADERS, timeout=TIMEOUT) #import requests

"""This cell displays the `resp` object, which represents the HTTP response from the `START_URL`. A `<Response [200]>` output indicates a successful request."""

resp

"""This cell retrieves the 'Content-Type' header from the HTTP response and stores it in the `ctype` variable. This is used to check if the content is HTML before parsing."""

ctype = resp.headers.get("Content-Type", "")

"""This cell displays the value of the `ctype` variable to check if response is valid HTML"""

ctype

"""This cell uses BeautifulSoup to parse the HTML content from the `resp.text` and creates a BeautifulSoup object named `soup`."""

soup = BeautifulSoup(resp.text, "html.parser")

"""This cell iterates through a list of HTML tags (script, style, noscript, etc.) and removes them from the parsed HTML (`soup`) to clean the content."""

for tag in soup(["script", "style", "noscript", "template", "svg", "canvas", "iframe", "picture", "source"]):
        tag.decompose()

"""This cell iterates through another list of HTML tags (header, footer, nav, aside) and removes them from the parsed HTML (`soup`)."""

for tag in soup(["header", "footer", "nav", "aside"]):
        tag.decompose()

"""This cell finds all HTML comments in the parsed HTML (`soup`) and extracts them."""

for c in soup.find_all(string=lambda text: isinstance(text, Comment)):
        c.extract()

"""This cell extracts the text content from the cleaned HTML (`soup`), using newline characters as separators and stripping leading/trailing whitespace. The result is stored in the `text` variable."""

text = soup.get_text(separator="\n", strip=True)

"""This cell displays the extracted and cleaned text content of the initial page."""

text

"""This cell uses a regular expression to replace two or more consecutive newline characters with a single newline character in the extracted text, further cleaning the content."""

text = re.sub(r"\n{2,}", "\n", text)

"""This cell displays the text after removing excessive newlines."""

text

"""This cell initializes an empty list called `all_texts` which will be used to store the extracted text content from all crawled pages."""

all_texts = []

"""This cell appends the text extracted from the initial page to the `all_texts` list."""

all_texts.append(text)

"""This cell extracts all URLs from the `href` attributes of `<a>` tags in the parsed HTML (`soup`). It constructs absolute URLs, removes fragments, and adds unique URLs to the `all_urls` list. Finally, it prints the list of extracted URLs."""

all_urls = []
for a in soup.find_all("a", href=True):
  abs_url = urljoin("https://docs.snowflake.com/en/guides", a["href"])
  #print(abs_url)
  abs_url, _ = urldefrag(abs_url)
  new_url = abs_url
  if new_url not in all_urls:
    all_urls.append(new_url)
print(all_urls)

"""This cell displays the number of unique URLs found on the initial page."""

len(all_urls)

"""This cell iterates through the `all_urls` list, visits each URL, checks if the content type is HTML, and if so, extracts and cleans the text content similar to the initial page. The extracted text from each valid HTML page is appended to the `all_texts` list."""

for url in all_urls:
  resp = requests.get(url, headers=HEADERS, timeout=TIMEOUT)
  ctype = resp.headers.get("Content-Type", "")
  if not ("text/html" in ctype.lower() or "application/xhtml+xml" in ctype.lower()):
    continue
  else:
    #print(url)
    soup = BeautifulSoup(resp.text, "html.parser")
    for tag in soup(["script", "style", "noscript", "template", "svg", "canvas", "iframe", "picture", "source"]):
        tag.decompose()
    for tag in soup(["header", "footer", "nav", "aside"]):
        tag.decompose()
    for c in soup.find_all(string=lambda text: isinstance(text, Comment)):
        c.extract()
    text = soup.get_text(separator="\n", strip=True)
    text = re.sub(r"\n{2,}", "\n", text)
    all_texts.append(text)
    #print(text)

