"""This cell imports the `FAISS` vector store from `langchain_community.vectorstores` and `RecursiveCharacterTextSplitter` from `langchain_text_splitters`. It then initializes a `RecursiveCharacterTextSplitter` with specified separators, chunk size, and chunk overlap for breaking down text into smaller pieces (chunks)."""

